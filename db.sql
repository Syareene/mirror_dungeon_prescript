CREATE DATABASE IF NOT EXISTS mirror_dungeon DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci;
USE mirror_dungeon;

CREATE TABLE IF NOT EXISTS packs (
    id INT AUTO_INCREMENT PRIMARY KEY,
    text VARCHAR(255) NOT NULL COMMENT 'パック名',
    locations VARCHAR(50) NOT NULL COMMENT '出現階層 (カンマ区切り例: "1" または "1,2")',
    appear6to10 TINYINT(1) NOT NULL DEFAULT 0 COMMENT '6-10層に出現するか (0:無効, 1:有効)',
    appear11to15 TINYINT(1) NOT NULL DEFAULT 0 COMMENT '11-15層に出現するか (0:無効, 1:有効)',
    image_path VARCHAR(255) NOT NULL COMMENT '画像ファイルパス',
    created_at DATETIME DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

